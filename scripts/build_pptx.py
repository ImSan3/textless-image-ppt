#!/usr/bin/env python3
"""Build PPTX slides from generated text-free backgrounds and editable text.

JSON input coordinates are pixels in each original background. Backgrounds must
already have been generated by an image tool and visually checked for text.
"""
import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageFont
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import MSO_ANCHOR, MSO_AUTO_SIZE, PP_ALIGN
from pptx.oxml.ns import qn
from pptx.oxml.xmlchemy import OxmlElement
from pptx.util import Inches, Pt


def rgb(value):
    value = value.lstrip('#')
    if len(value) != 6 or any(c not in '0123456789abcdefABCDEF' for c in value):
        raise ValueError(f'Expected a six-digit RGB color: {value!r}')
    return tuple(bytes.fromhex(value))


def east_asian_font(run, family):
    run.font.name = family
    props = run._r.get_or_add_rPr()
    ea = props.find(qn('a:ea'))
    if ea is None:
        ea = OxmlElement('a:ea')
        props.append(ea)
    ea.set('typeface', family)


def add_notes(slide, content, family):
    frame = slide.notes_slide.notes_text_frame
    frame.text = content
    for paragraph in frame.paragraphs:
        for run in paragraph.runs:
            east_asian_font(run, family)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--spec', required=True, type=Path)
    ap.add_argument('--output', required=True, type=Path)
    ap.add_argument('--background-dir', required=True, type=Path)
    ap.add_argument('--metrics-font', type=Path, help='Optional local font file used only to warn about likely text overflow')
    ap.add_argument('--metrics-font-index', type=int, default=0)
    ap.add_argument('--max-aspect-error', type=float, default=0.03, help='Reject source aspect ratio relative error above this; default 0.03')
    ap.add_argument('--force', action='store_true', help='Allow overwriting output PPTX and generated background files')
    args = ap.parse_args()
    spec_path = args.spec.expanduser().resolve()
    spec = json.loads(spec_path.read_text(encoding='utf-8'))
    page = spec.get('page', {})
    page_w = float(page.get('width_in', 7.5))
    page_h = float(page.get('height_in', 10))
    output_w = int(page.get('render_width_px', 3840))
    if page_w <= 0 or page_h <= 0 or output_w <= 0:
        raise ValueError('Page size and output width must be positive')
    output_h = round(output_w * page_h / page_w)
    family = page.get('font_family', '宋体')
    bg_color = rgb(page.get('background_color', 'FBF9F4'))
    slides = spec.get('slides', [])
    if not isinstance(slides, list) or not slides:
        raise ValueError('spec.slides must be a nonempty array')

    out = args.output.expanduser().resolve()
    backgrounds = args.background_dir.expanduser().resolve()
    paths = [backgrounds / f'{n:02d}_无字底图.png' for n in range(1, len(slides) + 1)]
    if not args.force:
        existing = [p for p in [out, *paths] if p.exists()]
        if existing:
            raise FileExistsError(f'Output exists; choose another name or pass --force: {existing[0]}')
    out.parent.mkdir(parents=True, exist_ok=True)
    backgrounds.mkdir(parents=True, exist_ok=True)

    prs = Presentation()
    prs.slide_width = Inches(page_w)
    prs.slide_height = Inches(page_h)
    alignments = {'left': PP_ALIGN.LEFT, 'center': PP_ALIGN.CENTER, 'right': PP_ALIGN.RIGHT}

    for number, (item, output_bg) in enumerate(zip(slides, paths), 1):
        source = Path(item['background']).expanduser()
        if not source.is_absolute():
            source = spec_path.parent / source
        source = source.resolve()
        if source == output_bg:
            raise ValueError(f'Slide {number}: background output would overwrite source')
        image = Image.open(source).convert('RGB')
        src_w, src_h = image.size
        error = abs((src_w / src_h) / (page_w / page_h) - 1)
        if error > args.max_aspect_error:
            raise ValueError(f'Slide {number}: image aspect differs by {error:.1%}; regenerate a matching image')
        scale = min(output_w / src_w, output_h / src_h)
        scaled_w, scaled_h = round(src_w * scale), round(src_h * scale)
        pad_x, pad_y = (output_w - scaled_w) // 2, (output_h - scaled_h) // 2
        canvas = Image.new('RGB', (output_w, output_h), bg_color)
        canvas.paste(image.resize((scaled_w, scaled_h), Image.Resampling.LANCZOS), (pad_x, pad_y))
        canvas.save(output_bg, compress_level=4)
        slide = prs.slides.add_slide(prs.slide_layouts[6])
        slide.shapes.add_picture(str(output_bg), 0, 0, width=prs.slide_width, height=prs.slide_height)
        for text_item in item.get('text', []):
            content = text_item['text']
            if not isinstance(content, str) or '\n' in content or '\r' in content:
                raise ValueError(f'Slide {number}: each text item must be a single line; use separate text boxes')
            x, y, width, height = map(float, text_item['box_px'])
            if x < 0 or y < 0 or width <= 0 or height <= 0 or x + width > src_w or y + height > src_h:
                raise ValueError(f'Slide {number}: text box outside the source background: {text_item["box_px"]}')
            pt = float(text_item.get('font_pt', 18))
            if pt <= 0:
                raise ValueError('font_pt must be positive')
            if args.metrics_font:
                pixels = max(1, round(pt * (output_w / page_w) / 72))
                font = ImageFont.truetype(str(args.metrics_font), pixels, index=args.metrics_font_index)
                if font.getlength(content) > width * scale:
                    print(f'WARNING: slide {number}, text may overflow: {content}', file=sys.stderr)
            left = Inches((x * scale + pad_x) / output_w * page_w)
            top = Inches((y * scale + pad_y) / output_h * page_h)
            box_w = Inches(width * scale / output_w * page_w)
            box_h = Inches(height * scale / output_h * page_h)
            shape = slide.shapes.add_textbox(left, top, box_w, box_h)
            frame = shape.text_frame
            frame.clear()
            frame.auto_size = MSO_AUTO_SIZE.NONE
            frame.word_wrap = False
            frame.margin_left = frame.margin_right = frame.margin_top = frame.margin_bottom = 0
            frame.vertical_anchor = MSO_ANCHOR.MIDDLE
            paragraph = frame.paragraphs[0]
            align = text_item.get('align', 'center')
            if align not in alignments:
                raise ValueError(f'Unknown alignment: {align}')
            paragraph.alignment = alignments[align]
            paragraph.space_before = paragraph.space_after = Pt(0)
            run = paragraph.add_run()
            run.text = content
            east_asian_font(run, text_item.get('font_family', family))
            run.font.size = Pt(pt)
            run.font.bold = bool(text_item.get('bold', True))
            run.font.color.rgb = RGBColor(*rgb(text_item.get('color', '1A1A1A')))
        add_notes(slide, item.get('notes', ''), family)
        print(f'Slide {number}: one background, {len(item.get("text", []))} editable text boxes; {output_bg}')
    prs.save(out)
    print(f'Saved: {out} ({page_w:g} x {page_h:g} in)')


if __name__ == '__main__':
    main()
